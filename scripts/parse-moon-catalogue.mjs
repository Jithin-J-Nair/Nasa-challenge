import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const PDF_URL = 'https://www.nasa.gov/wp-content/uploads/2024/02/final-catalogue-of-manmade-material-on-the-moon.pdf';
const pdfPath = process.env.MOON_CATALOGUE_PDF && resolve(process.env.MOON_CATALOGUE_PDF);
const cachePath = resolve('data/moon-catalogue-extract.md');

// The project keeps an extracted-text cache because this sandbox cannot always
// establish TLS to nasa.gov. On a maintainer machine, point MOON_CATALOGUE_PDF
// at the named NASA PDF and this exact parser will refresh the cache via
// pdftotext before producing the browser module.
if (pdfPath && existsSync(pdfPath)) {
  execFileSync('pdftotext', ['-layout', pdfPath, cachePath], { stdio: 'inherit' });
}
const source = await readFile(cachePath, 'utf8');

let section = 'Catalogue';
const rows = [];
for (const line of source.split(/\r?\n/)) {
  const heading = line.match(/^#{1,4}\s+(.+?)\s*$/);
  if (heading) {
    section = heading[1];
    continue;
  }
  // The web/PDF extraction normalizes its tables to two pipe-separated cells.
  // Header and separator rows are not material lines and do not enter counts.
  const cells = line.match(/^\|(.*?)\|(.*?)\|\s*$/);
  if (!cells || /^OBJECT$/i.test(cells[1].trim()) || /^-+$/.test(cells[1].trim())) continue;
  const rawObject = cells[1];
  const object = rawObject.trim();
  if (!object) continue;
  const location = cells[2].trim();
  const quantityValues = [...object.matchAll(/\[(\d+)\]/g)].map((match) => Number(match[1]));
  const seeBelow = /\bsee (?:below|above|experiment)/i.test(object);
  // One pad space is normal Markdown table formatting; two or more preserve
  // an indented PDF sub-item in the checked-in extraction.
  const subItem = /^\s{2,}/.test(rawObject) || /^\([a-z]\)/i.test(object);
  rows.push({
    object,
    location,
    section,
    quantity: quantityValues.reduce((sum, value) => sum + value, 0),
    seeBelow,
    subItem,
  });
}

const directRows = rows.filter((row) => !row.seeBelow && !row.subItem);
const stats = {
  lineCount: rows.length,
  directObjectCount: directRows.length,
  bracketQuantitySum: rows.reduce((sum, row) => sum + row.quantity, 0),
  displayedCount: directRows.length,
  sourcePdf: PDF_URL,
  generatedFrom: pdfPath ? 'MOON_CATALOGUE_PDF via pdftotext' : 'checked-in NASA PDF text cache',
};

const browserModule = `// Generated by scripts/parse-moon-catalogue.mjs — do not hand edit.\nexport const MOON_CATALOGUE_SOURCE = ${JSON.stringify(PDF_URL)};\nexport const MOON_CATALOGUE_ROWS = ${JSON.stringify(rows, null, 2)};\nexport const MOON_CATALOGUE_STATS = ${JSON.stringify(stats, null, 2)};\n`;
await mkdir('src/data', { recursive: true });
await writeFile('src/data/moon-catalogue.generated.js', browserModule);

const method = `# Moon catalogue parsing method

**Source:** [NASA History Program, *Catalogue of Manmade Material on the Moon* (2012)](${PDF_URL}).

` + `This result is generated by \`scripts/parse-moon-catalogue.mjs\` from ${stats.generatedFrom}. To refresh from an original downloaded PDF, run \`MOON_CATALOGUE_PDF=path/to/final-catalogue-of-manmade-material-on-the-moon.pdf node scripts/parse-moon-catalogue.mjs\`; the script uses \`pdftotext -layout\` and the same parser.

## Counts from this parse

| method | result | treatment |
| --- | ---: | --- |
| (a) Material table lines | ${stats.lineCount} | Every parsed object line, including references and indented/sub-item rows. |
| (b) Direct object/location rows | ${stats.directObjectCount} | Excludes rows containing “see below/above/experiment” and marked sub-items. This is the **only count displayed in the UI**. |
| (c) Summed bracket quantities | ${stats.bracketQuantitySum} | Sums explicit \`[n]\` quantities only; it is not a unique-object total. |

The PDF is a hierarchical catalogue, not a flat inventory or a mass ledger. Blank, \`UNKNOWN\`, \`Crashed\`, and narrative locations are retained exactly as parsed. This site does not turn them into coordinates, infer missing locations, or claim a mass total.\n`;
await mkdir('docs', { recursive: true });
await writeFile('docs/MOON-CATALOGUE-METHOD.md', method);
console.log(`Parsed NASA Moon catalogue: ${stats.lineCount} lines; ${stats.directObjectCount} direct rows; ${stats.bracketQuantitySum} bracket quantity sum.`);
